create type public.policy_kind as enum (
  'TERMS',
  'PRIVACY'
);

-- الملف الشخصي: صف لكل حساب هاتف. حسابات الموظفين (بريد) لا ملف لها.
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text check (
    display_name is null
    or (
      char_length(display_name) between 2 and 40
      and display_name = btrim(display_name)
      and display_name !~ '[[:cntrl:]]'
    )
  ),
  region_id integer references public.regions (id),
  status public.account_status not null default 'ACTIVE',
  status_changed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index profiles_region_id_idx on public.profiles (region_id);

create trigger profiles_set_updated_at before update on public.profiles
  for each row execute function private.set_updated_at();

-- نصوص السياسات بإصدارات. سجل إضافة فقط: الموافقة تشير إلى النص الذي وافق عليه
-- المستخدم (SRS القسم 7، policy_consents). الساري لكل نوع هو أعلى إصدار.
create table public.policy_documents (
  id integer generated by default as identity primary key,
  kind public.policy_kind not null,
  version integer not null check (version > 0),
  title text not null check (char_length(btrim(title)) between 1 and 120),
  body text not null check (char_length(btrim(body)) > 0),
  -- نص مؤقت لم يعتمد قانونيًا بعد.
  is_placeholder boolean not null default false,
  published_at timestamptz not null default now(),
  unique (kind, version)
);

create trigger policy_documents_append_only
  before update or delete on public.policy_documents
  for each row execute function private.forbid_change();

create table public.policy_consents (
  user_id uuid not null references public.profiles (id) on delete cascade,
  document_id integer not null references public.policy_documents (id),
  accepted_at timestamptz not null default now(),
  primary key (user_id, document_id)
);

create index policy_consents_document_id_idx on public.policy_consents (document_id);

-- الصلاحيات: المالك يقرأ صفه فقط. النصوص تقرأ عبر get_current_policies().
