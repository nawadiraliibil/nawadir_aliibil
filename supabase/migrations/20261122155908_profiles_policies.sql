create function public.get_current_policies()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object(
      'id', d.id, 'kind', d.kind, 'version', d.version, 'title', d.title,
      'body', d.body, 'is_placeholder', d.is_placeholder, 'published_at', d.published_at)
    order by d.kind), '[]'::jsonb)
  from private.current_policy_documents() d
$$;

comment on function public.get_current_policies() is
  'النصوص السارية للشروط والخصوصية. متاحة للزائر والمستخدم.';

