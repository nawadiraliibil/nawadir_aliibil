-- إنشاء الملف الشخصي عند إنشاء حساب هاتف.
create function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.phone is not null then
    insert into public.profiles (id) values (new.id)
    on conflict (id) do nothing;
  end if;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_auth_user();

-- معرف المستخدم صاحب الجلسة وله ملف شخصي؛ وإلا خطأ.
create function private.require_user()
returns uuid
language plpgsql
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    perform private.raise_error('AUTH_REQUIRED');
  end if;
  if not exists (select 1 from public.profiles p where p.id = v_uid) then
    perform private.raise_error('FORBIDDEN', pg_catalog.jsonb_build_object('reason', 'no_profile'));
  end if;
  return v_uid;
end;
$$;

-- النصوص السارية: أعلى إصدار لكل نوع.
create function private.current_policy_documents()
returns setof public.policy_documents
language sql
stable
set search_path = ''
as $$
  select distinct on (d.kind) d.*
  from public.policy_documents d
  order by d.kind, d.version desc
$$;

-- النصوص السارية التي لم يوافق عليها المستخدم بعد.
create function private.pending_policy_ids(p_user uuid)
returns integer[]
language sql
stable
set search_path = ''
as $$
  select coalesce(pg_catalog.array_agg(d.id order by d.kind), array[]::integer[])
  from private.current_policy_documents() d
  where not exists (
    select 1 from public.policy_consents c
    where c.user_id = p_user and c.document_id = d.id
  )
$$;

-- شرط النشر والتعديل (AD-FR-003): حساب فعال، بيانات مكتملة، موافقة على النصوص السارية.
create function private.assert_can_publish(p_user uuid)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v_profile public.profiles;
  v_missing text[] := array[]::text[];
  v_pending integer[];
begin
  select * into v_profile from public.profiles p where p.id = p_user;
  if not found then
    perform private.raise_error('FORBIDDEN', pg_catalog.jsonb_build_object('reason', 'no_profile'));
  end if;

  if v_profile.status <> 'ACTIVE' then
    perform private.raise_error('ACCOUNT_SUSPENDED');
  end if;

  if v_profile.display_name is null then
    v_missing := v_missing || 'display_name'::text;
  end if;
  if v_profile.region_id is null then
    v_missing := v_missing || 'region_id'::text;
  end if;
  if pg_catalog.cardinality(v_missing) > 0 then
    perform private.raise_error(
      'PROFILE_INCOMPLETE',
      pg_catalog.jsonb_build_object('fields', pg_catalog.to_jsonb(v_missing))
    );
  end if;

  v_pending := private.pending_policy_ids(p_user);
  if pg_catalog.cardinality(v_pending) > 0 then
    perform private.raise_error(
      'POLICIES_NOT_ACCEPTED',
      pg_catalog.jsonb_build_object('document_ids', pg_catalog.to_jsonb(v_pending))
    );
  end if;
end;
$$;

create function private.account_json(p_user uuid)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select pg_catalog.jsonb_build_object(
    'id', p.id,
    'display_name', p.display_name,
    'region_id', p.region_id,
    'status', p.status,
    'created_at', p.created_at,
    'profile_complete', (p.display_name is not null and p.region_id is not null),
    'pending_policies', coalesce((
      select pg_catalog.jsonb_agg(
        pg_catalog.jsonb_build_object('id', d.id, 'kind', d.kind, 'version', d.version, 'title', d.title)
        order by d.kind)
      from private.current_policy_documents() d
      where d.id = any (private.pending_policy_ids(p.id))
    ), '[]'::jsonb),
    'can_publish', (
      p.status = 'ACTIVE'
      and p.display_name is not null
      and p.region_id is not null
      and pg_catalog.cardinality(private.pending_policy_ids(p.id)) = 0
    )
  )
  from public.profiles p
  where p.id = p_user
$$;

