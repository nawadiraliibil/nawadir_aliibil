returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  return private.account_json(private.require_user());
end;
$$;

comment on function public.get_my_account() is
  'ملف المستخدم صاحب الجلسة، والنصوص التي تنتظر موافقته، وأهليته للنشر.';

create function public.update_my_profile(p_display_name text, p_region_id integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := private.require_user();
  v_name text := btrim(pg_catalog.regexp_replace(coalesce(p_display_name, ''), '\s+', ' ', 'g'));
  v_fields text[] := array[]::text[];
  v_profile public.profiles;
begin
  select * into v_profile from public.profiles p where p.id = v_uid for update;

  if v_profile.status <> 'ACTIVE' then
    perform private.raise_error('ACCOUNT_SUSPENDED');
  end if;

  if char_length(v_name) not between 2 and 40 or v_name ~ '[[:cntrl:]]' then
    v_fields := v_fields || 'display_name'::text;
  end if;

  -- المنطقة فعالة، أو هي منطقته الحالية التي عطلت لاحقًا.
  if p_region_id is null or not exists (
    select 1 from public.regions r
    where r.id = p_region_id
      and (r.is_active or r.id = v_profile.region_id)
  ) then
    v_fields := v_fields || 'region_id'::text;
  end if;

  if pg_catalog.cardinality(v_fields) > 0 then
    perform private.raise_error(
      'VALIDATION_FAILED',
      pg_catalog.jsonb_build_object('fields', pg_catalog.to_jsonb(v_fields))
    );
  end if;

  update public.profiles p
    set display_name = v_name, region_id = p_region_id
    where p.id = v_uid;

  return private.account_json(v_uid);
end;
$$;

comment on function public.update_my_profile(text, integer) is
  'حفظ اسم العرض والمنطقة لصاحب الجلسة.';

create function public.accept_policies(p_document_ids integer[])
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := private.require_user();
begin
  -- تقبل الموافقة على النصوص السارية فقط.
  if p_document_ids is null
    or pg_catalog.cardinality(p_document_ids) = 0
    or exists (
      select 1 from pg_catalog.unnest(p_document_ids) as t (id)
      where t.id is null
        or t.id not in (select d.id from private.current_policy_documents() d)
    )
  then
    perform private.raise_error(
      'VALIDATION_FAILED',
      pg_catalog.jsonb_build_object('fields', pg_catalog.jsonb_build_array('document_ids'))
    );
  end if;

  insert into public.policy_consents (user_id, document_id)
  select v_uid, t.id
  from (select distinct id from pg_catalog.unnest(p_document_ids) as u (id)) t
  on conflict (user_id, document_id) do nothing;

  return private.account_json(v_uid);
end;
$$;

comment on function public.accept_policies(integer[]) is
  'تسجيل موافقة صاحب الجلسة على نصوص سارية. تكرار الطلب لا يغير تاريخ الموافقة.';

grant execute on function public.get_current_policies() to anon, authenticated;
