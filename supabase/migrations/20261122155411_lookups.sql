-- دوال مساعدة عامة للـtriggers
create function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create function private.forbid_change()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  perform private.raise_error(
    'APPEND_ONLY',
    pg_catalog.jsonb_build_object('table', tg_table_name, 'operation', tg_op)
  );
  return null;
end;
$$;

comment on function private.forbid_change() is
  'trigger يمنع UPDATE وDELETE على جداول الإضافة فقط.';

-- المناطق
create table public.regions (
  id integer generated by default as identity primary key,
  name_ar text not null unique check (char_length(btrim(name_ar)) between 1 and 60),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- المدن: كل مدينة تتبع منطقة واحدة.
create table public.cities (
  id integer generated by default as identity primary key,
  region_id integer not null references public.regions (id),
  name_ar text not null check (char_length(btrim(name_ar)) between 1 and 60),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (region_id, name_ar)
);

-- السلالات. requires_note: قيمة «أخرى» التي تستلزم توضيحًا نصيًا من المعلن.
create table public.breeds (
  id integer generated by default as identity primary key,
  name_ar text not null unique check (char_length(btrim(name_ar)) between 1 and 60),
  requires_note boolean not null default false,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger regions_set_updated_at before update on public.regions
  for each row execute function private.set_updated_at();
create trigger cities_set_updated_at before update on public.cities
  for each row execute function private.set_updated_at();
create trigger breeds_set_updated_at before update on public.breeds
  for each row execute function private.set_updated_at();

